// Writes THIRD_PARTY_NOTICES.md: every package that ends up inside the app or the phone build, with
// its license, source URL and full license text. Run after `npm install`; the installer ships the file.
import fs from 'node:fs'
import path from 'node:path'

const ROOTS = ['@anthropic-ai/sdk', '@capacitor/android', '@capacitor/core', '@fontsource/inter',
  '@fontsource/source-serif-4', '@modelcontextprotocol/sdk', '@monaco-editor/react', 'jsqr', 'katex',
  'monaco-editor', 'openai', 'playwright-core', 'qrcode', 'react', 'react-dom', 'react-markdown',
  'rehype-katex', 'remark-gfm', 'remark-math', 'zod']
const nm = 'node_modules'
const seen = new Map()
const find = (n) => fs.existsSync(path.join(nm, n, 'package.json')) ? path.join(nm, n) : null
const walk = (n) => {
  if (seen.has(n)) return
  const dir = find(n)
  if (!dir) return
  const j = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'))
  seen.set(n, { dir, j })
  for (const d of Object.keys({ ...j.dependencies, ...j.optionalDependencies })) walk(d)
}
ROOTS.forEach(walk)

let out = '# Third-party notices\n\nAgenticOps Desk includes the open-source packages below. Each stays under its own license; the text is reproduced in full. Generated by `scripts/third-party-notices.mjs`.\n\n'
for (const [n, { dir, j }] of [...seen].sort((a, b) => a[0].localeCompare(b[0]))) {
  const lic = typeof j.license === 'string' ? j.license : JSON.stringify(j.license ?? j.licenses ?? 'UNKNOWN')
  const repo = String(j.repository?.url ?? j.repository ?? j.homepage ?? '').replace(/^git\+/, '')
  const file = fs.readdirSync(dir).find((f) => /^(licen[sc]e|copying)/i.test(f))
  const text = file ? fs.readFileSync(path.join(dir, file), 'utf8').trim() : '(no license file in the package; license field above)'
  out += `## ${n} ${j.version}\n\nLicense: ${lic}\nSource: ${repo}\n\n\`\`\`\n${text}\n\`\`\`\n\n`
}
fs.writeFileSync('THIRD_PARTY_NOTICES.md', out)
console.log(`${seen.size} packages`)
const odd = [...seen].filter(([, { j }]) => !/^(MIT|ISC|Apache-2\.0|BSD-[23]-Clause|OFL-1\.1|0BSD|BlueOak-1\.0\.0|Unlicense|CC0-1\.0)$/.test(typeof j.license === 'string' ? j.license : ''))
if (odd.length) console.log('Check by hand:', odd.map(([n, { j }]) => `${n} (${JSON.stringify(j.license)})`).join(', '))
